#!/usr/bin/env python3
"""Generate the baseline harness poms. Each harness = correct deps for one style."""
import json, os, sys

VERSIONS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "skill", "versions.json")))
SER_VER, SER_PW_VER = VERSIONS["serenity"], VERSIONS["serenityPlaywrightModules"]

SER = "net.serenity-bdd"
HARNESSES = {
  # name: (serenity version, [artifacts], extra deps xml)
  "h-po-selenium":   (SER_VER,  ["serenity-core", "serenity-junit5"], ""),
  "h-sp-selenium":   (SER_VER,  ["serenity-core", "serenity-junit5", "serenity-screenplay", "serenity-screenplay-webdriver", "serenity-ensure"], ""),
  "h-sp-rest":       (SER_VER,  ["serenity-core", "serenity-junit5", "serenity-screenplay", "serenity-screenplay-rest", "serenity-rest-assured", "serenity-ensure"], ""),
  "h-cuke-sp":       (SER_VER,  ["serenity-core", "serenity-junit5", "serenity-screenplay", "serenity-screenplay-webdriver", "serenity-cucumber", "serenity-ensure"],
                       "cuke"),
  "h-po-playwright": (SER_PW_VER, ["serenity-core", "serenity-junit5", "serenity-playwright"], "pw"),
  "h-sp-playwright": (SER_PW_VER, ["serenity-core", "serenity-junit5", "serenity-screenplay", "serenity-screenplay-playwright", "serenity-playwright"], "pw"),
  # every style available: used for unnamed-style prompts and for seeded projects (the model must choose or follow)
  "h-all":           (SER_PW_VER, ["serenity-core", "serenity-junit5", "serenity-screenplay", "serenity-screenplay-webdriver",
                                 "serenity-screenplay-rest", "serenity-rest-assured", "serenity-screenplay-playwright",
                                 "serenity-playwright", "serenity-cucumber", "serenity-ensure"], "cuke+pw"),
}

# seeded projects: h-all plus the skill's compiling example for one style already in src/test
SEEDS = {"seed-po-selenium": "po-selenium", "seed-sp-selenium": "sp-selenium",
         "seed-sp-playwright": "sp-playwright", "seed-cuke-sp": "cuke-sp"}

def dep(g, a, v=None, scope="test"):
    ver = f"<version>{v}</version>" if v else ""
    return f"    <dependency><groupId>{g}</groupId><artifactId>{a}</artifactId>{ver}<scope>{scope}</scope></dependency>"

def pom(name, ser, arts, extra):
    deps = [dep(SER, a, "${serenity.version}") for a in arts]
    deps += [
        dep("org.junit.jupiter", "junit-jupiter", "${junit-jupiter.version}"),
        dep("org.junit.platform", "junit-platform-suite", "${junit-platform.version}"),
        dep("org.assertj", "assertj-core", "3.27.7"),
        dep("org.slf4j", "slf4j-simple", "2.0.17"),
    ]
    if "cuke" in extra:
        deps += [dep("io.cucumber", "cucumber-java", "${cucumber.version}"),
                 dep("io.cucumber", "cucumber-junit-platform-engine", "${cucumber.version}")]
    if "pw" in extra:
        deps += [dep("com.microsoft.playwright", "playwright", "${playwright.version}")]
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by gen.py: do not edit by hand -->
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>eval</groupId>
  <artifactId>{name}</artifactId>
  <version>1.0-SNAPSHOT</version>
  <properties>
    <maven.compiler.release>17</maven.compiler.release>
    <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>
    <serenity.version>{ser}</serenity.version>
    <junit-jupiter.version>{VERSIONS['junit']}</junit-jupiter.version>
    <junit-platform.version>{VERSIONS['junit']}</junit-platform.version>
    <cucumber.version>{VERSIONS['cucumber'] if ser == SER_VER else '7.34.2'}</cucumber.version>
    <playwright.version>1.52.0</playwright.version>
  </properties>
  <dependencyManagement>
    <dependencies>
      <dependency><groupId>org.junit</groupId><artifactId>junit-bom</artifactId><version>${{junit-jupiter.version}}</version><type>pom</type><scope>import</scope></dependency>
    </dependencies>
  </dependencyManagement>
  <dependencies>
{os.linesep.join(deps)}
  </dependencies>
  <build>
    <plugins>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-surefire-plugin</artifactId>
        <version>3.5.1</version>
        <configuration>
          <!-- generated code names its test and runner classes freely -->
          <includes><include>**/*.java</include></includes>
        </configuration>
      </plugin>
      <plugin>
        <groupId>org.apache.maven.plugins</groupId>
        <artifactId>maven-failsafe-plugin</artifactId>
        <version>3.5.1</version>
      </plugin>
      <plugin>
        <groupId>net.serenity-bdd.maven.plugins</groupId>
        <artifactId>serenity-maven-plugin</artifactId>
        <version>${{serenity.version}}</version>
        <executions>
          <execution><id>serenity-reports</id><phase>post-integration-test</phase><goals><goal>aggregate</goal></goals></execution>
        </executions>
      </plugin>
    </plugins>
  </build>
</project>
"""

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    for name, (ser, arts, extra) in HARNESSES.items():
        d = os.path.join(here, name)
        os.makedirs(os.path.join(d, "src/test/java"), exist_ok=True)
        os.makedirs(os.path.join(d, "src/test/resources"), exist_ok=True)
        open(os.path.join(d, "pom.xml"), "w").write(pom(name, ser, arts, extra))
        print("wrote", name)
    import shutil
    ex = os.path.join(here, "..", "..", "skill", "serenity-bdd", "examples")
    for seed, example in SEEDS.items():
        d = os.path.join(here, seed)
        shutil.rmtree(d, ignore_errors=True)
        shutil.copytree(os.path.join(here, "h-all"), d)
        shutil.copytree(os.path.join(ex, example), os.path.join(d, "src/test/java"), dirs_exist_ok=True)
        feats = os.path.join(d, "src/test/java/features")
        if os.path.isdir(feats):
            shutil.move(feats, os.path.join(d, "src/test/resources/features"))
        print("seeded", seed)
