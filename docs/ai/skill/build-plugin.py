#!/usr/bin/env python3
"""Generate the Claude Code plugin marketplace repository from this directory.

usage: build-plugin.py OUTPUT_DIR

OUTPUT_DIR is the working copy of the separate marketplace repository (it may be a git checkout; .git and a
LICENSE file that is already there are left alone). Everything else in it is regenerated, so the repository must
never be edited by hand: fix the source here and run this again.

Layout written:

  .claude-plugin/marketplace.json
  plugins/serenity-bdd/.claude-plugin/plugin.json
  plugins/serenity-bdd/skills/serenity-bdd/...       the skill (SKILL.md, references, examples, scripts)
  plugins/serenity-bdd/agents/serenity-test-reviewer.md
  templates/agents-md/AGENTS.*.md                    not loaded by the plugin; copied into a project by hand
  README.md

The version of the plugin is the Serenity version in versions.json: Claude Code only offers an update when the
version string changes, so bump versions.json (and re-verify, see release-check.sh) for every release of the guidance.
"""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_SKILL = os.path.join(HERE, "serenity-bdd")
SRC_AGENT = os.path.join(HERE, "agents", "serenity-test-reviewer.md")
SRC_VARIANTS = os.path.join(HERE, "..", "agents-md", "variants")

MARKETPLACE = "serenity"
PLUGIN = "serenity-bdd"
REPO = "serenity-bdd/serenity-ai"          # the marketplace repository on GitHub
SOURCE_REPO = "https://github.com/serenity-bdd/serenity-core"
CHECKS_URL = SOURCE_REPO + "/blob/main/docs/ai/skill/"
HOMEPAGE = "https://serenity-bdd.github.io/docs/ai/ai_using_assistants"

SKIP_NAMES = {"check-examples.sh", "__pycache__", ".DS_Store"}


def die(msg):
    sys.exit("build-plugin.py: " + msg)


def clean(out):
    existing = [n for n in os.listdir(out) if n not in (".git", "LICENSE")]
    if existing and not os.path.exists(os.path.join(out, ".claude-plugin", "marketplace.json")):
        die("%s is not empty and was not generated by this script; refusing to clear it" % out)
    for name in existing:
        if name in (".git", "LICENSE"):
            continue
        p = os.path.join(out, name)
        shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)


def copy_skill(dest):
    def ignore(_dir, names):
        return [n for n in names if n in SKIP_NAMES or n.endswith(".pyc")]
    shutil.copytree(SRC_SKILL, dest, ignore=ignore)
    # The checks live in serenity-core, one level above the skill there; point at them by URL.
    n = 0
    for root, _dirs, files in os.walk(dest):
        for f in files:
            if not f.endswith(".md"):
                continue
            p = os.path.join(root, f)
            s = open(p).read()
            t, k = re.subn(r"(?<![\w./-])\.\./\.\./([A-Za-z0-9_-]+(?:/[A-Za-z0-9_.-]+)*)", lambda m: CHECKS_URL + m.group(1), s)
            if k:
                open(p, "w").write(t)
                n += k
    # nothing may still point out of the plugin
    for root, _dirs, files in os.walk(dest):
        for f in files:
            if f.endswith(".md") and re.search(r"(?<![\w./-])\.\./\.\./", open(os.path.join(root, f)).read()):
                die("a link out of the plugin is left in %s" % os.path.join(root, f))
    return n


def write_agent(dest):
    s = open(SRC_AGENT).read()
    anchor = "or the path the caller gave)"
    if anchor not in s:
        die("the reviewer agent no longer contains %r; update build-plugin.py" % anchor)
    s = s.replace(anchor, "or the path the caller gave; when the Serenity plugin is installed, find them with Glob "
                          "`~/.claude/plugins/**/skills/serenity-bdd/references/review-checklist.md`)", 1)
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    open(dest, "w").write(s)


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")


def readme(version, pw):
    return """# Serenity BDD for AI coding assistants

A Claude Code plugin that helps an AI assistant write, fix and review [Serenity BDD](https://serenity-bdd.github.io) tests in Java. It describes **Serenity %(v)s** (Playwright modules %(pw)s).

> **Generated.** This repository is built from [`docs/ai`](%(src)s/tree/main/docs/ai) in `serenity-core` by `skill/build-plugin.py`. Do not edit it here: open the issue or pull request against `serenity-core`.

## Install

```
/plugin marketplace add %(repo)s
/plugin install %(plugin)s@%(mp)s
```

Then ask for Serenity work as usual ("add a Serenity test for the login page"). The skill loads when the request matches. To update later: `/plugin marketplace update %(mp)s`.

## What is in it

| Part | What it does |
|---|---|
| `serenity-bdd` skill | Picks the style (Page Objects with `@Steps`, Screenplay, Cucumber; Selenium, Playwright or REST) or asks which one you want, then loads the reference for it: the exact packages, a mistakes table, compiling examples. Also covers `serenity.conf`, running tests, reading results from the JSON files, upgrading, and troubleshooting by symptom. |
| `serenity-test-reviewer` agent | Reads new tests and the report and checks that scenarios state their intent in business English, are grouped by function, and assert what their titles claim. It reports and does not edit. |
| `templates/agents-md/` | One `AGENTS.md` per style, to copy into a project so the assistant stays in that style. A plugin does not load these; copy the one you need to the project root as `AGENTS.md` (or `CLAUDE.md`). |

The skill never defaults to one style: Page Objects, Screenplay and Cucumber are all supported ways of working.

## How far to trust it

Every class and method named in the guidance is checked against the released jars, and the examples compile and their tests run, on each release (`skill/release-check.sh` in `serenity-core`). The pass rates measured so far, and the limits (Claude models and Claude Code only, live sample sites, 2 to 3 runs per case), are in the [evaluation write-up](%(src)s/blob/main/docs/ai/baseline-results.md). Treat the guidance as experimental.

Not covered: mobile (Appium), Spring and Guice object factories, cloud and grid capabilities, and Gradle beyond Cucumber.

## Licence

Apache 2.0, like Serenity BDD.
""" % dict(v=version, pw=pw, src=SOURCE_REPO, repo=REPO, plugin=PLUGIN, mp=MARKETPLACE)


def main():
    if len(sys.argv) != 2:
        die("usage: build-plugin.py OUTPUT_DIR")
    out = os.path.abspath(sys.argv[1])
    V = json.load(open(os.path.join(HERE, "versions.json")))
    version = V["serenity"]
    os.makedirs(out, exist_ok=True)
    clean(out)

    plug = os.path.join(out, "plugins", PLUGIN)
    n = copy_skill(os.path.join(plug, "skills", PLUGIN))
    write_agent(os.path.join(plug, "agents", "serenity-test-reviewer.md"))

    tpl = os.path.join(out, "templates", "agents-md")
    os.makedirs(tpl)
    for f in sorted(os.listdir(SRC_VARIANTS)):
        if f.startswith("AGENTS.") and f.endswith(".md"):
            shutil.copy(os.path.join(SRC_VARIANTS, f), tpl)

    write_json(os.path.join(plug, ".claude-plugin", "plugin.json"), {
        "name": PLUGIN,
        "version": version,
        "description": "Write, fix and review Serenity BDD tests in Java: Page Objects, Screenplay and Cucumber, with Selenium, Playwright or REST. Describes Serenity %s." % version,
        "author": {"name": "Serenity BDD"},
        "homepage": HOMEPAGE,
        "repository": "https://github.com/" + REPO,
        "license": "Apache-2.0",
        "keywords": ["serenity-bdd", "testing", "bdd", "screenplay", "selenium", "playwright", "cucumber", "java"],
    })
    write_json(os.path.join(out, ".claude-plugin", "marketplace.json"), {
        "name": MARKETPLACE,
        "description": "Agent skills and subagents for Serenity BDD test automation",
        "owner": {"name": "Serenity BDD"},
        "plugins": [{
            "name": PLUGIN,
            "source": "./plugins/" + PLUGIN,
            "description": "Skill and test-reviewer agent for writing Serenity BDD tests with an AI assistant (Serenity %s)." % version,
            "category": "testing",
            "tags": ["serenity-bdd", "testing", "bdd"],
        }],
    })
    open(os.path.join(out, "README.md"), "w").write(readme(version, V["serenityPlaywrightModules"]))
    open(os.path.join(out, ".gitignore"), "w").write(".DS_Store\n__pycache__/\n*.pyc\n")
    print("wrote %s (plugin %s %s; %d links to the checks rewritten)" % (out, PLUGIN, version, n))


if __name__ == "__main__":
    main()
